"""Узлы AST и система типов языка РАЗУМ."""

from __future__ import annotations

from dataclasses import dataclass, field

# --- Типы -------------------------------------------------------------------


@dataclass(frozen=True)
class Тип:
    """Тип РАЗУМА.

    вид: 'цел' | 'без' | 'бул' | 'сим' | 'пусто' | 'стр' | 'указ'
       | 'масс' | 'срез' | 'запись' | 'функ' | 'любой'
    """

    вид: str
    размер: int = 8  # байт (для скаляров; записи/массивы считаются отдельно)
    база: "Тип | None" = None  # для указ/масс/срез
    n: int = 0  # длина массива
    имя: str = ""  # имя записи/синонима


ЦЕЛ8 = Тип("цел", 1)
ЦЕЛ16 = Тип("цел", 2)
ЦЕЛ32 = Тип("цел", 4)
ЦЕЛ64 = Тип("цел", 8)
БЕЗ8 = Тип("без", 1)
БЕЗ16 = Тип("без", 2)
БЕЗ32 = Тип("без", 4)
БЕЗ64 = Тип("без", 8)
БУЛ = Тип("бул", 1)
СИМ = Тип("сим", 1)
ПУСТО = Тип("пусто", 0)
СТР = Тип("стр", 8)  # значение стр — указатель на {данные, длина}
ЛЮБОЙ = Тип("любой", 8)

ПРИМИТИВЫ = {
    "цел8": ЦЕЛ8,
    "цел16": ЦЕЛ16,
    "цел32": ЦЕЛ32,
    "цел64": ЦЕЛ64,
    "без8": БЕЗ8,
    "без16": БЕЗ16,
    "без32": БЕЗ32,
    "без64": БЕЗ64,
    "бул": БУЛ,
    "сим": СИМ,
    "пусто": ПУСТО,
    "стр": СТР,
}


def указ(на: Тип) -> Тип:
    """Указатель на тип."""
    return Тип("указ", 8, база=на)


def масс(элем: Тип, n: int) -> Тип:
    """Массив фиксированной длины."""
    return Тип("масс", 0, база=элем, n=n)


def срез(элем: Тип) -> Тип:
    """Срез: {данные *Т, длина без64}."""
    return Тип("срез", 8, база=элем)


def запись(имя: str) -> Тип:
    """Ссылка на объявленную запись по имени."""
    return Тип("запись", 0, имя=имя)


def функ_тип(парамы: list, возвр: Тип) -> Тип:
    """Тип функции (для указателей на функции)."""
    t = Тип("функ", 8)
    object.__setattr__(t, "_парамы", парамы)
    object.__setattr__(t, "_возвр", возвр)
    return t


def знаковый(t: Тип) -> bool:
    """Истина, если тип знаковый целочисленный."""
    return t.вид == "цел"


def целочисл(t: Тип) -> bool:
    """Истина для целых, беззнаковых, бул, сим и указателей."""
    return t.вид in ("цел", "без", "бул", "сим", "указ", "функ", "стр")


