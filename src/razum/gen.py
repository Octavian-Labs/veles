"""Генератор кода РАЗУМА: AST -> текст ИСКРЫ (.иск).

Модель: каждое выражение оставляет результат в АКК; бинарные операции —
через ВСТЕК/ИЗСТЕКА. Локальные переменные и параметры адресуются через
УКК (устойчиво к push-подсчётам внутри выражений).

Соглашения вызовов:
- Windows: СЧТ/ДАН/Р8/Р9 + теневая область 32 байта; стек-аргументы выше.
- Linux (SysV): ПРМ/ИСТ/ДАН/СЧТ/Р8/Р9; без тени.

стр — указатель на статическую запись {КВАД данные, КВАД длина}.
Записи и массивы хранятся инлайн в кадре; выражение над ними даёт адрес.
"""

from __future__ import annotations

from . import nodes as N
from .errors import RazError

# смещения полей стр/срез
_ПОЛЯ_ПАРЫ = {"данные": (0, N.указ(N.БЕЗ8)), "длина": (8, N.БЕЗ64)}


class _Контекст:
    """Состояние генерации одной функции."""

    def __init__(self):
        self.локалы: dict[str, tuple[int, N.Тип]] = {}  # имя -> (УКК-оффсет, тип)
        self.парамы: dict[str, tuple[int, N.Тип]] = {}
        self.циклы: list[tuple[str, str]] = []  # (метка_шага, метка_конца)
        self.отложи: list = []
        self.фрейм = 0
        self.выход = ""  # метка эпилога
        self.возвр = N.ПУСТО


class Генератор:
    """Преобразует программу РАЗУМА в текст ассемблера ИСКРА."""

    def __init__(self, target: str = "windows", опт: int = 1):
        self.target = target
        self.опт = опт
        if target == "windows":
            self.арг_реги = ["СЧТ", "ДАН", "Р8", "Р9"]
            self.тень = 32
        else:
            self.арг_реги = ["ПРМ", "ИСТ", "ДАН", "СЧТ", "Р8", "Р9"]
            self.тень = 0
        self.код: list[str] = []
        self.данные: list[str] = []
        self.импорты: dict[str, list[str]] = {}
        self.консты: dict[str, int] = {}
        self.записи: dict[str, tuple[int, dict[str, tuple[int, N.Тип]]]] = {}
        self.синонимы: dict[str, N.Тип] = {}
        self.функции: dict[str, tuple[list, N.Тип, bool]] = {}
        self.методы: dict[tuple[str, str], tuple[str, list, N.Тип]] = {}
        self.перечи: dict[str, dict[str, int]] = {}
        self.нужны_стд: set[str] = set()
        self._стр_n = 0
        self._lbl = 0
        self._ctx = _Контекст()
        self._глуб = 0  # выданные ВСТЕК (в восьмибайтовках)
        self._есть_главная = False

    # --- вывод ----------------------------------------------------------------

    def e(self, s: str):
        self.код.append("    " + s)

    def метка(self, s: str):
        self.код.append(s + ":")

    def _новая(self, вид: str) -> str:
        self._lbl += 1
        return f"м{self._lbl}_{вид}"

    # --- типы -----------------------------------------------------------------

    def _реш_тип(self, t: N.Тип) -> N.Тип:
        while t.вид == "запись" and t.имя in self.синонимы:
            t = self.синонимы[t.имя]
        return t

    def размер(self, t: N.Тип) -> int:
        t = self._реш_тип(t)
        if t.вид == "масс":
            return self.размер(t.база) * t.n
        if t.вид == "запись":
            if t.имя not in self.записи:
                raise RazError(f"неизвестная запись {t.имя!r}")
            return self.записи[t.имя][0]
        if t.вид in ("стр", "срез", "указ", "функ", "любой"):
            return 8
        return t.размер

    def _загрузить(self, операнд: str, t: N.Тип):
        """Загружает значение типа t из операнда в АКК."""
        sz = self.размер(t)
        if sz >= 8:
            self.e(f"ПЕР АКК, {операнд}")
        elif sz == 4:
            if N.знаковый(t):
                self.e(f"ЗНАКРАСШД АКК, ДВСЛОВО{операнд}")
            else:
                self.e(f"ПЕР АККМ, {операнд}")
        elif sz == 2:
            м = "ЗНАКРАСШ" if N.знаковый(t) else "БЕЗРАСШ"
            self.e(f"{м} АКК, СЛОВО{операнд}")
        else:
            м = "ЗНАКРАСШ" if N.знаковый(t) else "БЕЗРАСШ"
            self.e(f"{м} АКК, БАЙТ{операнд}")

    def _сохранить(self, операнд: str, t: N.Тип):
        """Сохраняет АКК в операнд по размеру типа."""
        sz = self.размер(t)
        рег = {8: "АКК", 4: "АККМ", 2: "АККП", 1: "АККБ"}[max(1, min(sz, 8))]
        self.e(f"ПЕР {операнд}, {рег}")

    def _загрузить_рег(self, рег: str, операнд: str, t: N.Тип):
        """Загружает аргумент в регистр с учётом размера/знака типа."""
        sz = self.размер(t)
        if sz >= 8:
            self.e(f"ПЕР {рег}, {операнд}")
        elif sz == 4:
            if N.знаковый(t):
                self.e(f"ЗНАКРАСШД {рег}, ДВСЛОВО{операнд}")
            else:
                self.e(f"ПЕР {рег}М, {операнд}")
        elif sz == 2:
            м = "ЗНАКРАСШ" if N.знаковый(t) else "БЕЗРАСШ"
            self.e(f"{м} {рег}, СЛОВО{операнд}")
        else:
            м = "ЗНАКРАСШ" if N.знаковый(t) else "БЕЗРАСШ"
            self.e(f"{м} {рег}, БАЙТ{операнд}")

    # --- константы ------------------------------------------------------------

    def _конст(self, e) -> int:
        """Вычисляет константное выражение во время компиляции."""
        if isinstance(e, N.Число):
            return e.знач
        if isinstance(e, N.Бул):
            return int(e.знач)
        if isinstance(e, N.Имя):
            if e.имя in self.консты:
                return self.консты[e.имя]
            raise RazError(f"константа {e.имя!r} не определена", e.строка)
        if isinstance(e, N.Поле) and isinstance(e.об, N.Имя):
            if e.об.имя in self.перечи and e.имя in self.перечи[e.об.имя]:
                return self.перечи[e.об.имя][e.имя]
        if isinstance(e, N.Ун) and e.оп == "-":
            return -self._конст(e.выр)
        if isinstance(e, N.Привед):
            return self._конст(e.выр)
        if isinstance(e, N.Размер):
            t = e.цель if isinstance(e.цель, N.Тип) else self._тип_выр(e.цель)
            return self.размер(t)
        if isinstance(e, N.Бин):
            a, b = self._конст(e.лев), self._конст(e.прав)
            ops = {
                "+": a + b,
                "-": a - b,
                "*": a * b,
                "/": a // b if b else 0,
                "%": a % b if b else 0,
                "&": a & b,
                "|": a | b,
                "^": a ^ b,
                "<<": a << b,
                ">>": a >> b,
                "==": int(a == b),
                "!=": int(a != b),
                "<": int(a < b),
                "<=": int(a <= b),
                ">": int(a > b),
                ">=": int(a >= b),
            }
            if e.оп in ops:
                return ops[e.оп]
        raise RazError("не константное выражение", getattr(e, "строка", 0))

    def _совместим(self, цель: N.Тип, выр, строка: int):
        """Проверка присваиваемости: литералы — по диапазону, остальное — по виду."""
        цель = self._реш_тип(цель)
        ст = self._реш_тип(self._тип_выр(выр))
        if цель.вид == "любой" or ст.вид == "любой":
            return
        # имя-константа раскрывается в литерал — диапазон проверяем по значению
        if isinstance(выр, N.Имя) and выр.имя in self.консты:
            выр = N.Число(self.консты[выр.имя], выр.строка)
        if isinstance(выр, (N.Число, N.Бул)) and цель.вид in (
            "цел",
            "без",
            "сим",
            "бул",
        ):
            # числовой литерал — проверяем диапазон целевого типа
            v = int(выр.знач)
            бит = self.размер(цель) * 8
            if N.знаковый(цель):
                ок = -(1 << (бит - 1)) <= v < (1 << (бит - 1))
            else:
                ок = 0 <= v < (1 << бит)
            if not ок:
                raise RazError(
                    f"литерал {v} не влезает в {цель.вид}{цель.размер * 8}",
                    строка,
                )
            return
        if цель.вид == "указ" and ст.вид == "указ":
            бц, бс = self._реш_тип(цель.база), self._реш_тип(ст.база)
            if бц.вид == "пусто" or бс.вид == "пусто":
                return  # *пусто — универсальный указатель
            if бц.вид != бс.вид or (бц.вид == "запись" and бц.имя != бс.имя):
                raise RazError(
                    f"несовместимые указатели: *{бц.вид} и *{бс.вид}", строка
                )
            return
        if цель.вид == "функ" and ст.вид == "функ":
            return
        if цель.вид != ст.вид:
            raise RazError(f"несовместимые типы: {цель.вид} и {ст.вид}", строка)
        if цель.вид == "запись" and цель.имя != ст.имя:
            raise RazError(f"разные записи: {цель.имя} и {ст.имя}", строка)
        if цель.вид in ("срез", "масс") and цель.база != ст.база:
            raise RazError("несовместимые базовые типы", строка)

    # --- тип выражения ----------------------------------------------------------

    def _тип_выр(self, e) -> N.Тип:
        """Статический тип выражения без генерации кода."""
        if isinstance(e, N.Число):
            return N.ЦЕЛ64
        if isinstance(e, N.Строка):
            return N.СТР
        if isinstance(e, N.Бул):
            return N.БУЛ
        if isinstance(e, N.ПустоЛит):
            return N.указ(N.ПУСТО)
        if isinstance(e, N.Имя):
            if e.имя in self._ctx.локалы:
                return self._ctx.локалы[e.имя][1]
            if e.имя in self._ctx.парамы:
                return self._ctx.парамы[e.имя][1]
            if e.имя in self.консты:
                return N.ЦЕЛ64
            if e.имя in self.функции:
                парамы, возвр, _ = self.функции[e.имя]
                return N.функ_тип([p.тип for p in парамы], возвр)
            raise RazError(f"неизвестное имя {e.имя!r}", e.строка)
        if isinstance(e, N.Бин):
            if e.оп in _СРАВ_БУЛ or e.оп in ("и", "или", "в"):
                return N.БУЛ
            return self._тип_выр(e.лев)
        if isinstance(e, N.Ун):
            return N.БУЛ if e.оп == "не" else self._тип_выр(e.выр)
        if isinstance(e, N.Адрес):
            return N.указ(self._тип_выр(e.выр))
        if isinstance(e, N.Разым):
            t = self._реш_тип(self._тип_выр(e.выр))
            if t.вид != "указ":
                raise RazError("разыменование не-указателя", e.строка)
            return t.база
        if isinstance(e, N.Поле):
            t = self._реш_тип(self._тип_выр(e.об))
            if t.вид in ("стр", "срез") and e.имя in _ПОЛЯ_ПАРЫ:
                return _ПОЛЯ_ПАРЫ[e.имя][1]
            if t.вид == "указ":
                t = self._реш_тип(t.база)
            if t.вид == "запись" and t.имя in self.записи:
                return self.записи[t.имя][1][e.имя][1]
            if e.об is not None and isinstance(e.об, N.Имя) and e.об.имя in self.перечи:
                return N.ЦЕЛ64
            raise RazError(f"нет поля {e.имя!r}", e.строка)
        if isinstance(e, N.Индекс):
            t = self._реш_тип(self._тип_выр(e.об))
            if t.вид in ("масс", "срез", "указ"):
                return t.база
            if t.вид == "стр":
                return N.СИМ
            raise RazError("индексация не-массива", e.строка)
        if isinstance(e, N.СрезДиап):
            t = self._реш_тип(self._тип_выр(e.об))
            if t.вид == "стр":
                return N.срез(N.СИМ)
            if t.вид in ("масс", "срез", "указ"):
                return N.срез(t.база)
            raise RazError("срез не-массива", e.строка)
        if isinstance(e, N.ЛитТип):
            return self._реш_тип(e.тип)
        if isinstance(e, N.Привед):
            return e.тип
        if isinstance(e, N.Размер):
            return N.БЕЗ64
        if isinstance(e, N.Новый):
            return N.указ(e.тип)
        if isinstance(e, N.Вызов):
            if isinstance(e.функ, N.Поле):
                m = self._метод_ищи(e)
                if m:
                    return m[2]
                raise RazError("вызов метода не найден", e.строка)
            if isinstance(e.функ, N.Имя):
                имя = e.функ.имя
                if имя in self.функции:
                    return self.функции[имя][1]
                if имя == "освободи":
                    return N.ПУСТО
                if имя == "выдели":
                    return N.указ(N.БЕЗ8)
                слот = self._ctx.локалы.get(имя) or self._ctx.парамы.get(имя)
                if слот and self._реш_тип(слот[1]).вид == "функ":
                    return self._реш_тип(слот[1]).вз or N.ПУСТО
            return N.ЛЮБОЙ
        if isinstance(e, N.Диап):
            raise RazError("диапазон допустим в «для», «выбор» и «в»", e.строка)
        return N.ЛЮБОЙ

    # --- выражения ------------------------------------------------------------

    def _выр(self, e) -> N.Тип:
        """Генерирует выражение; результат — в АКК. Возвращает тип."""
        if isinstance(e, N.Число):
            self.e(f"ПЕР АКК, {e.знач}")
            return N.ЦЕЛ64
        if isinstance(e, N.Строка):
            i = self._стр_интерн(e.знач)
            self.e(f"АДР АКК, [стр_{i}]")
            return N.СТР
        if isinstance(e, N.Бул):
            self.e(f"ПЕР АКК, {int(e.знач)}")
            return N.БУЛ
        if isinstance(e, N.ПустоЛит):
            self.e("ПЕР АКК, 0")
            return N.указ(N.ПУСТО)
        if isinstance(e, N.Имя):
            return self._выр_имя(e)
        if isinstance(e, N.Привед):
            self._выр(e.выр)
            return self._реш_тип(e.тип)
        if isinstance(e, N.Размер):
            t = e.цель if isinstance(e.цель, N.Тип) else self._тип_выр(e.цель)
            self.e(f"ПЕР АКК, {self.размер(t)}")
            return N.БЕЗ64
        if isinstance(e, N.Новый):
            sz = self.размер(e.тип)
            self.нужны_стд.add("выдели")
            self.e(f"ПЕР СЧТ, {sz}")
            self._пад_и_вызов("стд_выдели")
            return N.указ(e.тип)
        if isinstance(e, N.Адрес):
            self._адрес(e.выр)
            return N.указ(self._тип_выр(e.выр))
        if isinstance(e, N.Разым):
            t = self._выр(e.выр)
            t = self._реш_тип(t)
            if t.вид != "указ":
                raise RazError("разыменование не-указателя", e.строка)
            self._загрузить("[АКК]", t.база)
            return t.база
        if isinstance(e, N.Поле):
            t = self._поле_адрес(e)
            self._загрузить("[АКК]", t)
            return t
        if isinstance(e, N.Индекс):
            t = self._индекс_адрес(e)
            self._загрузить("[АКК]", t)
            return t
        if isinstance(e, N.Ун):
            return self._унар(e)
        if isinstance(e, N.Бин):
            return self._бин(e)
        if isinstance(e, N.Вызов):
            return self._вызов(e)
        if isinstance(e, N.СрезДиап):
            return self._срез(e)
        if isinstance(e, N.ЛитТип):
            return self._литерал(e)
        if isinstance(e, N.Диап):
            raise RazError("диапазон вне контекста итерации", e.строка)
        raise RazError(f"не поддержан узел {type(e).__name__}", 0)

    def _выр_имя(self, e: N.Имя) -> N.Тип:
        """Имя: локальная, параметр, константа, элемент перечисления, функция."""
        имя = e.имя
        if имя in self._ctx.локалы:
            off, t = self._ctx.локалы[имя]
            t = self._реш_тип(t)
            if t.вид in ("запись", "масс"):
                # значение записи/массива — её адрес
                self.e(f"АДР АКК, [УКК-{off}]")
                return t
            self._загрузить(f"[УКК-{off}]", t)
            return t
        if имя in self._ctx.парамы:
            off, t = self._ctx.парамы[имя]
            t = self._реш_тип(t)
            if t.вид in ("запись", "масс"):
                self.e(f"АДР АКК, [УКК{off:+}]")
                return t
            self._загрузить(f"[УКК{off:+}]", t)
            return t
        if имя in self.консты:
            self.e(f"ПЕР АКК, {self.консты[имя]}")
            return N.ЦЕЛ64
        for п, эл in self.перечи.items():
            if имя in эл:
                self.e(f"ПЕР АКК, {эл[имя]}")
                return N.ЦЕЛ64
        if имя in self.функции:
            парамы, возвр, внеш = self.функции[имя]
            self.e(f"АДР АКК, [{имя if внеш else 'ф_' + имя.replace('.', '_')}]")
            return N.функ_тип([p.тип for p in парамы], возвр)
        raise RazError(f"неизвестное имя {имя!r}", e.строка)

    def _адрес(self, e):
        """Оставляет в АКК адрес lvalue."""
        if isinstance(e, N.Имя):
            if e.имя in self._ctx.локалы:
                off, _ = self._ctx.локалы[e.имя]
                self.e(f"АДР АКК, [УКК-{off}]")
                return
            if e.имя in self._ctx.парамы:
                off, _ = self._ctx.парамы[e.имя]
                self.e(f"АДР АКК, [УКК{off:+}]")
                return
            raise RazError(f"нельзя взять адрес {e.имя!r}", e.строка)
        if isinstance(e, N.Разым):
            self._выр(e.выр)
            return
        if isinstance(e, N.Поле):
            self._поле_адрес(e)
            return
        if isinstance(e, N.Индекс):
            self._индекс_адрес(e)
            return
        raise RazError("выражение не имеет адреса", getattr(e, "строка", 0))

    def _поле_адрес(self, e: N.Поле) -> N.Тип:
        """Адрес поля в АКК; возвращает тип поля."""
        t_об = self._реш_тип(self._тип_выр(e.об))
        # перечисление: Имя.Элемент — константа
        if isinstance(e.об, N.Имя) and e.об.имя in self.перечи:
            raise RazError("элемент перечисления — не адрес", e.строка)
        if t_об.вид in ("стр", "срез"):
            if e.имя not in _ПОЛЯ_ПАРЫ:
                raise RazError(f"у {t_об.вид} нет поля {e.имя!r}", e.строка)
            off, ft = _ПОЛЯ_ПАРЫ[e.имя]
            self._выр(e.об)  # значение стр/срез — указатель на пару
            if off:
                self.e(f"ДОБ АКК, {off}")
            return ft
        if t_об.вид == "указ":
            база = self._реш_тип(t_об.база)
            if база.вид == "запись":
                off, ft = self._поле_записи(база.имя, e.имя, e.строка)
                self._выр(e.об)
                if off:
                    self.e(f"ДОБ АКК, {off}")
                return ft
            if база.вид in ("стр", "срез") and e.имя in _ПОЛЯ_ПАРЫ:
                off, ft = _ПОЛЯ_ПАРЫ[e.имя]
                self._выр(e.об)
                if off:
                    self.e(f"ДОБ АКК, {off}")
                return ft
        if t_об.вид == "запись":
            off, ft = self._поле_записи(t_об.имя, e.имя, e.строка)
            self._адрес(e.об)
            if off:
                self.e(f"ДОБ АКК, {off}")
            return ft
        raise RazError(f"поле {e.имя!r} неприменимо", e.строка)

    def _поле_записи(self, имя_записи: str, поле: str, строка: int):
        if имя_записи not in self.записи:
            raise RazError(f"неизвестная запись {имя_записи!r}", строка)
        поля = self.записи[имя_записи][1]
        if поле not in поля:
            raise RazError(f"у записи {имя_записи} нет поля {поле!r}", строка)
        return поля[поле]

    def _индекс_адрес(self, e: N.Индекс) -> N.Тип:
        """Адрес элемента в АКК; возвращает тип элемента."""
        t_об = self._реш_тип(self._тип_выр(e.об))
        if t_об.вид == "стр":
            # стр[i] — байт данных
            self._выр(e.инд)
            self.e("ВСТЕК АКК")
            self._глуб += 1
            self._выр(e.об)  # указатель на {данные, длина}
            self.e("ПЕР АКК, [АКК]")
            self.e("ИЗСТЕКА СЧТ")
            self._глуб -= 1
            self.e("ДОБ АКК, СЧТ")
            return N.СИМ
        if t_об.вид == "срез":
            элем = t_об.база
            esz = self.размер(элем)
            self._выр(e.инд)
            if esz != 1:
                self.e(f"УМН АКК, АКК, {esz}")
            self.e("ВСТЕК АКК")
            self._глуб += 1
            self._выр(e.об)
            self.e("ПЕР АКК, [АКК]")  # .данные
            self.e("ИЗСТЕКА СЧТ")
            self._глуб -= 1
            self.e("ДОБ АКК, СЧТ")
            return элем
        if t_об.вид == "указ" or t_об.вид == "масс":
            элем = self._реш_тип(t_об.база)
            esz = self.размер(элем)
            self._выр(e.инд)
            if esz != 1:
                self.e(f"УМН АКК, АКК, {esz}")
            self.e("ВСТЕК АКК")
            self._глуб += 1
            if t_об.вид == "масс":
                self._адрес(e.об)  # массив инлайн — его адрес
            else:
                self._выр(e.об)
            self.e("ИЗСТЕКА СЧТ")
            self._глуб -= 1
            self.e("ДОБ АКК, СЧТ")
            return элем
        raise RazError("индексация не-массива", e.строка)

    def _унар(self, e: N.Ун) -> N.Тип:
        if e.оп == "-":
            t = self._выр(e.выр)
            self.e("ОТР АКК")
            return t
        if e.оп == "не":
            self._выр(e.выр)
            self.e("ПРОВ АКК, АКК")
            self.e("УСТРАВНО АККБ")
            self.e("БЕЗРАСШ АКК, АККБ")
            return N.БУЛ
        raise RazError(f"неизвестный унарный {e.оп!r}", e.строка)

    _БИН_АРИФ = {"+": "ДОБ", "-": "ВЫЧ", "&": "И", "|": "ИЛИ", "^": "ИИЛИ"}

    def _бин(self, e: N.Бин) -> N.Тип:
        оп = e.оп
        if оп == "и":
            конец = self._новая("иложь")
            self._выр(e.лев)
            self.e("ПРОВ АКК, АКК")
            self.e(f"РАВНО {конец}")
            self._выр(e.прав)
            self.метка(конец)
            return N.БУЛ
        if оп == "или":
            конец = self._новая("иист")
            self._выр(e.лев)
            self.e("ПРОВ АКК, АКК")
            self.e(f"НЕРАВНО {конец}")
            self._выр(e.прав)
            self.метка(конец)
            return N.БУЛ
        if оп == "в":
            return self._проверка_диапазона(e)
        if оп in _СРАВ_БУЛ:
            lt = self._тип_выр(e.лев)
            rt = self._тип_выр(e.прав)
            uns = not (N.знаковый(lt) and N.знаковый(rt))
            self._выр(e.лев)
            self.e("ВСТЕК АКК")
            self._глуб += 1
            self._выр(e.прав)
            self.e("ПЕР СЧТ, АКК")
            self.e("ИЗСТЕКА АКК")
            self._глуб -= 1
            self.e("СРАВ АКК, СЧТ")
            cc = _CC_UNSIGNED[оп] if uns else _CC_SIGNED[оп]
            self.e(f"{cc} АККБ")
            self.e("БЕЗРАСШ АКК, АККБ")
            return N.БУЛ
        lt = self._тип_выр(e.лев)
        self._выр(e.лев)
        self.e("ВСТЕК АКК")
        self._глуб += 1
        self._выр(e.прав)
        self.e("ПЕР СЧТ, АКК")
        self.e("ИЗСТЕКА АКК")
        self._глуб -= 1
        if оп in self._БИН_АРИФ:
            self.e(f"{self._БИН_АРИФ[оп]} АКК, СЧТ")
            return lt
        if оп == "*":
            self.e("УМН АКК, СЧТ")
            return lt
        if оп in ("/", "%"):
            if N.знаковый(lt):
                self.e("РАСШ")
                self.e("ДЕЛ СЧТ")
            else:
                self.e("ПЕР ДАН, 0")
                self.e("ДЕЛБ СЧТ")
            if оп == "%":
                self.e("ПЕР АКК, ДАН")
            return lt
        if оп in ("<<", ">>"):
            м = "СДЛ" if оп == "<<" else ("СДПА" if N.знаковый(lt) else "СДП")
            self.e(f"{м} АКК, СЧТБ")
            return lt
        raise RazError(f"неизвестный оператор {оп!r}", e.строка)

    def _проверка_диапазона(self, e: N.Бин) -> N.Тип:
        """х в a..b / a..=b — булева проверка."""
        диап = e.прав
        ложь = self._новая("вне")
        конец = self._новая("вкон")
        self._выр(e.лев)  # х
        self.e("ВСТЕК АКК")
        self._глуб += 1
        self._выр(диап.лев)  # lo
        self.e("ВСТЕК АКК")
        self._глуб += 1
        self._выр(диап.прав)  # hi
        self.e("ПЕР ДАН, АКК")
        self.e("ИЗСТЕКА СЧТ")
        self.e("ИЗСТЕКА АКК")
        self._глуб -= 2
        uns = not N.знаковый(self._тип_выр(e.лев))
        м_меньше = "НИЖЕ" if uns else "МЕНЬШЕ"
        м_больше = "ВЫШЕ" if uns else "БОЛЬШЕ"
        м_болрав = "ВЫШРАВ" if uns else "БОЛРАВ"
        self.e("СРАВ АКК, СЧТ")
        self.e(f"{м_меньше} {ложь}")
        self.e("СРАВ АКК, ДАН")
        self.e(f"{м_больше if диап.вкл else м_болрав} {ложь}")
        self.e("ПЕР АКК, 1")
        self.e(f"ПРЫГ {конец}")
        self.метка(ложь)
        self.e("ПЕР АКК, 0")
        self.метка(конец)
        return N.БУЛ

    # --- вызовы ----------------------------------------------------------------

    def _пад_и_вызов(self, цель: str):
        """ВЫЗОВ с выравниванием стека по текущей глубине ВСТЕК."""
        лишние = (self._глуб * 8) % 16
        пад = (16 - лишние) % 16
        if пад:
            self.e(f"ВЫЧ УКС, {пад}")
        self.e(f"ВЫЗОВ {цель}")
        if пад:
            self.e(f"ДОБ УКС, {пад}")

    def _метод_ищи(self, e: N.Вызов):
        """Ищет метод (запись, имя) для вызова об.метод(...)."""
        if not isinstance(e.функ, N.Поле):
            return None
        t_об = self._реш_тип(self._тип_выр(e.функ.об))
        rec = None
        if t_об.вид == "запись":
            rec = t_об.имя
        elif t_об.вид == "указ" and self._реш_тип(t_об.база).вид == "запись":
            rec = self._реш_тип(t_об.база).имя
        if rec is None:
            return None
        return self.методы.get((rec, e.функ.имя))

    def _вызов(self, e: N.Вызов) -> N.Тип:
        цель = e.функ
        if isinstance(цель, N.Поле):
            m = self._метод_ищи(e)
            if m is None:
                raise RazError("поле не является методом", e.строка)
            асм_имя, парамы, возвр = m
            t_об = self._реш_тип(self._тип_выр(цель.об))
            приёмник = (
                N.Адрес(цель.об, цель.об.строка) if t_об.вид == "запись" else цель.об
            )
            return self._вызов_ядро(
                асм_имя,
                парамы,
                возвр,
                [(None, приёмник)] + list(e.арги),
                e.строка,
                асм_имя,
            )
        if not isinstance(цель, N.Имя):
            # косвенный вызов через произвольное выражение-указатель
            ft = self._реш_тип(self._тип_выр(цель))
            if ft.вид != "функ":
                raise RazError("вызов не-функции", e.строка)
            парамы = [N.Парам(f"а{i}", t) for i, t in enumerate(ft.арги)]
            return self._вызов_ядро(
                None, парамы, ft.вз or N.ПУСТО, e.арги, e.строка, косв=цель
            )
        имя = цель.имя
        if имя == "освободи":
            if len(e.арги) != 1:
                raise RazError("освободи(указ) — один аргумент", e.строка)
            self.нужны_стд.add("освободи")
            self._выр(e.арги[0][1])
            self.e("ПЕР СЧТ, АКК")
            self._пад_и_вызов("стд_освободи")
            return N.ПУСТО
        if имя == "выдели":
            if len(e.арги) != 1:
                raise RazError("выдели(размер) — один аргумент", e.строка)
            self.нужны_стд.add("выдели")
            self._выр(e.арги[0][1])
            self.e("ПЕР СЧТ, АКК")
            self._пад_и_вызов("стд_выдели")
            return N.указ(N.БЕЗ8)
        if имя == "новый":
            raise RazError("новый(Тип) — без аргументов-выражений", e.строка)
        if имя not in self.функции:
            if имя in self._ctx.локалы or имя in self._ctx.парамы:
                t = self._реш_тип(
                    (self._ctx.локалы.get(имя) or self._ctx.парамы[имя])[1]
                )
                if t.вид != "функ":
                    raise RazError(f"{имя!r} — не функция", e.строка)
                парамы = [N.Парам(f"а{i}", x) for i, x in enumerate(t.арги)]
                return self._вызов_ядро(
                    None, парамы, t.вз or N.ПУСТО, e.арги, e.строка, косв=цель
                )
            raise RazError(f"неизвестная функция {имя!r}", e.строка)
        парамы, возвр, внеш = self.функции[имя]
        асм_имя = имя if внеш else f"ф_{имя.replace('.', '_')}"
        return self._вызов_ядро(асм_имя, парамы, возвр, e.арги, e.строка, имя)

    def _вызов_ядро(
        self, асм_имя, парамы, возвр, арги_исх, строка, описание="", косв=None
    ) -> N.Тип:
        """Общий код вызова: аргументы -> регистры/стек, ВЫЗОВ, результат в АКК."""
        # именованные аргументы -> позиционные
        арги = [None] * len(парамы)
        for имя_арг, выр in арги_исх:
            if имя_арг is None:
                try:
                    i = арги.index(None)
                except ValueError:
                    raise RazError("слишком много аргументов", строка) from None
                арги[i] = выр
            else:
                найден = [i for i, p in enumerate(парамы) if p.имя == имя_арг]
                if not найден:
                    raise RazError(f"нет параметра {имя_арг!r}", строка)
                if арги[найден[0]] is not None:
                    raise RazError(f"аргумент {имя_арг!r} задан дважды", строка)
                арги[найден[0]] = выр
        if any(a is None for a in арги):
            raise RazError(f"вызов {описание}: не хватает аргументов", строка)
        nreg = min(len(арги), len(self.арг_реги))
        стековых = len(арги) - nreg
        глуб0 = self._глуб
        # паддинг до начала: rsp должен быть ≡0 mod16 в точке ВЫЗОВ
        сумма = 8 * self._глуб + 8 * стековых + self.тень
        пад = (16 - сумма % 16) % 16
        if пад:
            self.e(f"ВЫЧ УКС, {пад}")
            self._глуб += пад // 8
        # вычисляем аргументы справа налево, кладём в стек
        for i in range(len(арги) - 1, -1, -1):
            self._выр(арги[i])
            self.e("ВСТЕК АКК")
            self._глуб += 1
        # указатель на функцию (косвенный вызов) — до извлечения аргументов
        if косв is not None:
            self._выр(косв)
            self.e("ПЕР Р11, АКК")
        # регистровые аргументы (сверху стека, в порядке)
        for i in range(nreg):
            рег = self.арг_реги[i]
            t = парамы[i].тип
            sz = self.размер(t)
            if sz == 8 or sz == 0:
                self.e(f"ИЗСТЕКА {рег}")
            else:
                # извлекаем и расширяем по типу параметра
                self.e("ИЗСТЕКА АКК")
                if sz == 4:
                    if N.знаковый(t):
                        self.e(f"ЗНАКРАСШД {рег}, АККМ")
                    else:
                        self.e(f"ПЕР {рег}М, АККМ")
                elif sz == 2:
                    м = "ЗНАКРАСШ" if N.знаковый(t) else "БЕЗРАСШ"
                    self.e(f"{м} {рег}, АККП")
                else:
                    м = "ЗНАКРАСШ" if N.знаковый(t) else "БЕЗРАСШ"
                    self.e(f"{м} {рег}, АККБ")
            self._глуб -= 1
        if self.тень:
            self.e(f"ВЫЧ УКС, {self.тень}")
        if косв is not None:
            self.e("ВЫЗОВ Р11")
        else:
            self.e(f"ВЫЗОВ {асм_имя}")
        # восстановление стека: тень + стек-аргументы + пад
        назад = self.тень + 8 * стековых + пад
        if назад:
            self.e(f"ДОБ УКС, {назад}")
        self._глуб = глуб0
        return возвр

    # --- срезы и литералы --------------------------------------------------------

    def _срез(self, e: N.СрезДиап) -> N.Тип:
        """об[a..b] -> срез {данные, длина} в скрытом слоте; АКК = его адрес."""
        t_об = self._реш_тип(self._тип_выр(e.об))
        if t_об.вид == "стр":
            элем, esz = N.СИМ, 1
        elif t_об.вид in ("масс", "срез", "указ"):
            элем = self._реш_тип(t_об.база)
            esz = self.размер(элем)
        else:
            raise RazError("срез не-массива", e.строка)
        off = self._слот_среза(e)
        # данные: база + лев*esz
        self._выр(e.диап.лев)
        if esz != 1:
            self.e(f"УМН АКК, АКК, {esz}")
        self.e("ВСТЕК АКК")
        self._глуб += 1
        if t_об.вид == "масс":
            self._адрес(e.об)
        else:
            self._выр(e.об)
            if t_об.вид in ("срез", "стр"):
                self.e("ПЕР АКК, [АКК]")  # .данные
        self.e("ИЗСТЕКА СЧТ")
        self._глуб -= 1
        self.e("ДОБ АКК, СЧТ")
        self.e(f"ПЕР [УКК-{off}], АКК")
        # длина: прав - лев (+1 если ..=)
        self._выр(e.диап.прав)
        self.e("ВСТЕК АКК")
        self._глуб += 1
        self._выр(e.диап.лев)
        self.e("ПЕР СЧТ, АКК")
        self.e("ИЗСТЕКА АКК")
        self._глуб -= 1
        self.e("ВЫЧ АКК, СЧТ")
        if e.диап.вкл:
            self.e("УВЕЛ АКК")
        self.e(f"ПЕР [УКК-{off - 8}], АКК")
        self.e(f"АДР АКК, [УКК-{off}]")
        return N.срез(элем)

    def _литерал(self, e: N.ЛитТип) -> N.Тип:
        """Тип{...} -> заполнение скрытого слота; АКК = его адрес."""
        t = self._реш_тип(e.тип)
        off = self._слот_лита(e)
        # пропущенные поля/элементы — нули
        sz = self.размер(t)
        цикл = self._новая("литноль")
        self.e(f"ПЕР СЧТ, {sz}")
        self.e(f"АДР ПРМ, [УКК-{off}]")
        self.метка(цикл)
        self.e("ПЕР БАЙТ[ПРМ], 0")
        self.e("УВЕЛ ПРМ")
        self.e("УМЕН СЧТ")
        self.e(f"НЕНОЛЬ {цикл}")
        if t.вид == "запись":
            поля = self.записи[t.имя][1]
            if any(имя is not None for имя, _ in e.элементы):
                поз = 0
                for имя_п, выр in e.элементы:
                    if имя_п is None:
                        имя_п = list(поля)[поз]
                    foff, ft = поля.get(имя_п, (None, None))
                    if foff is None:
                        raise RazError(f"у записи {t.имя} нет поля {имя_п!r}", e.строка)
                    self._совместим(ft, выр, e.строка)
                    self._выр(выр)
                    self._сохранить(f"[УКК-{off - foff}]", ft)
                    поз += 1
            else:
                список = list(поля.values())
                for i, (_, выр) in enumerate(e.элементы):
                    if i >= len(список):
                        raise RazError("слишком много полей в литерале", e.строка)
                    foff, ft = список[i]
                    self._совместим(ft, выр, e.строка)
                    self._выр(выр)
                    self._сохранить(f"[УКК-{off - foff}]", ft)
        elif t.вид == "масс":
            элем = self._реш_тип(t.база)
            esz = self.размер(элем)
            if len(e.элементы) > t.n:
                raise RazError("слишком много элементов в литерале", e.строка)
            for i, (_, выр) in enumerate(e.элементы):
                self._совместим(элем, выр, e.строка)
                self._выр(выр)
                self._сохранить(f"[УКК-{off - i * esz}]", элем)
        else:
            raise RazError("литерал {..} — только записи и массивы", e.строка)
        self.e(f"АДР АКК, [УКК-{off}]")
        return t

    def _слот_лита(self, e: N.ЛитТип) -> int:
        """Смещение скрытого слота литерала (выделяется при скане)."""
        if not hasattr(e, "_слот"):
            raise RazError("внутренняя: слот литерала не выделен", e.строка)
        return self._ctx.локалы[e._слот][0]

    def _слот_среза(self, e: N.СрезДиап) -> int:
        """Смещение скрытого слота пары {данные, длина}."""
        if not hasattr(e, "_слот"):
            raise RazError("внутренняя: слот среза не выделен", e.строка)
        return self._ctx.локалы[e._слот][0]

    # --- строки -----------------------------------------------------------------

    def _стр_интерн(self, s: str) -> int:
        """Интернирует строку в секцию данных; возвращает номер записи стр."""
        i = self._стр_n
        self._стр_n += 1
        байты = s.encode("utf-8")
        части = []
        буф = ""
        for c in s:
            if c in ('"', "\\") or ord(c) < 32:
                if буф:
                    части.append(f'"{буф}"')
                    буф = ""
                части += [str(b) for b in c.encode("utf-8")]
            else:
                буф += c
        if буф:
            части.append(f'"{буф}"')
        части.append("0")
        self.данные.append(f'стрд_{i}: БАЙТ {", ".join(части)}')
        self.данные.append(f"стр_{i}: КВАД стрд_{i}, {len(байты)}")
        return i

    # --- сканирование тела функции ----------------------------------------------

    def _скан_выр(self, e, порядок: list):
        """Выделяет скрытые слоты для литералов и срезов внутри выражения."""
        if e is None or isinstance(e, (N.Число, N.Строка, N.Бул, N.Имя, N.ПустоЛит)):
            return
        if isinstance(e, N.ЛитТип):
            t = self._реш_тип(e.тип)
            слот = f"_лит{self._lbl}"
            self._lbl += 1
            e._слот = слот
            порядок.append((слот, t, None))
            for _, в in e.элементы:
                self._скан_выр(в, порядок)
            return
        if isinstance(e, N.СрезДиап):
            слот = f"_срез{self._lbl}"
            self._lbl += 1
            e._слот = слот
            # пара {данные, длина} = 16 байт
            порядок.append((слот, N.масс(N.БЕЗ8, 16), None))
            self._скан_выр(e.об, порядок)
            self._скан_выр(e.диап.лев, порядок)
            self._скан_выр(e.диап.прав, порядок)
            return
        for поле in vars(e).values() if hasattr(e, "__dict__") else ():
            if isinstance(поле, list):
                for x in поле:
                    if isinstance(x, tuple):
                        for y in x:
                            self._скан_выр(y, порядок)
                    else:
                        self._скан_выр(x, порядок)
            else:
                self._скан_выр(поле, порядок)

    def _скан_тело(self, тело: list, порядок: list, имена: set):
        """Собирает объявления локальных переменных и скрытые слоты."""
        for s in тело:
            if isinstance(s, N.Объявл):
                if s.имя not in имена:
                    имена.add(s.имя)
                    порядок.append((s.имя, s.тип, s.выр))
                self._скан_выр(s.выр, порядок)
            elif isinstance(s, N.Конст):
                self.консты[s.имя] = self._конст(s.выр)
            elif isinstance(s, N.Присв):
                self._скан_выр(s.цель, порядок)
                self._скан_выр(s.выр, порядок)
            elif isinstance(s, N.ВырОп):
                self._скан_выр(s.выр, порядок)
            elif isinstance(s, N.Верни):
                self._скан_выр(s.выр, порядок)
            elif isinstance(s, N.Отложи):
                self._скан_выр(s.выр, порядок)
            elif isinstance(s, N.Если):
                for усл, т in s.рукава:
                    self._скан_выр(усл, порядок)
                    self._скан_тело(т, порядок, имена)
                if s.иначе:
                    self._скан_тело(s.иначе, порядок, имена)
            elif isinstance(s, N.Пока):
                self._скан_выр(s.усл, порядок)
                self._скан_тело(s.тело, порядок, имена)
            elif isinstance(s, N.Вечно):
                self._скан_тело(s.тело, порядок, имена)
            elif isinstance(s, N.Для):
                for k, имя in enumerate(s.имена):
                    if имя not in имена:
                        имена.add(имя)
                        if k == 0:
                            порядок.append((имя, N.ЦЕЛ64, None))
                        else:
                            # тип элемента выводится из итерируемого
                            порядок.append((имя, None, N.Индекс(s.итер, N.Число(0))))
                self._скан_выр(s.итер, порядок)
                слот = f"_предел{self._lbl}"
                self._lbl += 1
                порядок.append((слот, N.ЦЕЛ64, None))
                s._предел = слот
                self._скан_тело(s.тело, порядок, имена)
            elif isinstance(s, N.Выбор):
                self._скан_выр(s.выр, порядок)
                слот = f"_выбор{self._lbl}"
                self._lbl += 1
                порядок.append((слот, N.ЦЕЛ64, None))
                s._слот = слот
                for образцы, т in s.варианты:
                    for обр in образцы:
                        self._скан_выр(обр, порядок)
                    self._скан_тело(т, порядок, имена)
                if s.иначе:
                    self._скан_тело(s.иначе, порядок, имена)

    # --- операторы ------------------------------------------------------------

    def _оп(self, s):
        if isinstance(s, N.Объявл):
            self._объявл(s)
        elif isinstance(s, N.Конст):
            pass  # уже вычислена при сканировании
        elif isinstance(s, N.Присв):
            self._присв(s)
        elif isinstance(s, N.ВырОп):
            self._выр(s.выр)
        elif isinstance(s, N.Если):
            self._если(s)
        elif isinstance(s, N.Пока):
            self._пока(s)
        elif isinstance(s, N.Вечно):
            self._вечно(s)
        elif isinstance(s, N.Для):
            self._для(s)
        elif isinstance(s, N.Выбор):
            self._выбор(s)
        elif isinstance(s, N.Верни):
            if s.выр is not None:
                self._выр(s.выр)
            self.e(f"ПРЫГ {self._ctx.выход}")
        elif isinstance(s, N.Хватит):
            if not self._ctx.циклы:
                raise RazError("«хватит» вне цикла", s.строка)
            self.e(f"ПРЫГ {self._ctx.циклы[-1][1]}")
        elif isinstance(s, N.Следующий):
            if not self._ctx.циклы:
                raise RazError("«следующий» вне цикла", s.строка)
            self.e(f"ПРЫГ {self._ctx.циклы[-1][0]}")
        elif isinstance(s, N.Отложи):
            self._ctx.отложи.append(s.выр)
        elif isinstance(s, N.Искра):
            for стр in s.строки:
                if стр.strip():
                    self.e(self._искра_подстановка(стр))
        else:
            raise RazError(f"не поддержан оператор {type(s).__name__}", 0)

    def _искра_подстановка(self, стр: str) -> str:
        """Заменяет имена локалов/параметров в строке ИСКРЫ на [УКК±off]."""
        import re

        def подстановка(m):
            имя = m.group(0)
            if имя in self._ctx.локалы:
                off, _ = self._ctx.локалы[имя]
                return f"[УКК-{off}]"
            if имя in self._ctx.парамы:
                off, _ = self._ctx.парамы[имя]
                return f"[УКК+{off}]"
            return имя

        # комментарий «#» внутри искра-блока (комментарий ассемблера — «;»)
        if "#" in стр:
            голова, _, _ = стр.partition("#")
            стр = голова
        # слова из букв/цифр/подчёркивания, не часть метки «имя:» и не мнемоника
        return re.sub(r"(?<![\w.])\b[а-яА-ЯёЁa-zA-Z_]\w*\b(?!\s*:)", подстановка, стр)

    def _объявл(self, s: N.Объявл):
        off, t = self._ctx.локалы[s.имя]
        t = self._реш_тип(t)
        if s.выр is None:
            sz = self.размер(t)
            if sz <= 8:
                рег = {8: "", 4: "ДВСЛОВО", 2: "СЛОВО", 1: "БАЙТ"}[max(1, sz)]
                self.e(f"ПЕР {рег}[УКК-{off}], 0" if рег else f"ПЕР КВАД[УКК-{off}], 0")
            else:
                # обнуление блока
                цикл = self._новая("обнул")
                self.e(f"ПЕР СЧТ, {sz}")
                self.e(f"АДР ПРМ, [УКК-{off}]")
                self.метка(цикл)
                self.e("ПЕР БАЙТ[ПРМ], 0")
                self.e("УВЕЛ ПРМ")
                self.e("УМЕН СЧТ")
                self.e(f"НЕНОЛЬ {цикл}")
            return
        self._совместим(t, s.выр, s.строка)
        et = self._выр(s.выр)
        if t.вид == "любой":
            t = et
        if self._реш_тип(t).вид in ("запись", "масс") or self._реш_тип(
            self._тип_выр(s.выр)
        ).вид in ("запись", "масс"):
            # присваивание блоков: копируем байты
            sz = self.размер(t)
            self.e("ВСТЕК АКК")  # адрес источника
            self._глуб += 1
            self.e(f"АДР АКК, [УКК-{off}]")
            self.e("ПЕР ПРМ, АКК")
            self.e("ИЗСТЕКА ИСТ")
            self._глуб -= 1
            цикл = self._новая("коп")
            self.e(f"ПЕР СЧТ, {sz}")
            self.метка(цикл)
            self.e("ПЕР АККБ, БАЙТ[ИСТ]")
            self.e("ПЕР БАЙТ[ПРМ], АККБ")
            self.e("УВЕЛ ИСТ")
            self.e("УВЕЛ ПРМ")
            self.e("УМЕН СЧТ")
            self.e(f"НЕНОЛЬ {цикл}")
            return
        self._сохранить(f"[УКК-{off}]", t)

    def _присв(self, s: N.Присв):
        self._адрес(s.цель)
        t = self._тип_выр(s.цель)
        self._совместим(t, s.выр, s.строка)
        self.e("ВСТЕК АКК")
        self._глуб += 1
        self._выр(s.выр)
        if s.оп == "=":
            self.e("ПЕР СЧТ, АКК")
            self.e("ИЗСТЕКА ДАН")
            self._глуб -= 1
            sz = self.размер(t)
            рег = {8: "СЧТ", 4: "СЧТМ", 2: "СЧТП", 1: "СЧТБ"}[max(1, min(sz, 8))]
            self.e(f"ПЕР [ДАН], {рег}")
            return
        оп = s.оп[0]  # + - * / % & | ^
        self.e("ПЕР СЧТ, АКК")  # правое
        self.e("ИЗСТЕКА ДАН")  # адрес цели
        self._глуб -= 1
        if оп in ("+", "-", "&", "|", "^"):
            м = {"+": "ДОБ", "-": "ВЫЧ", "&": "И", "|": "ИЛИ", "^": "ИИЛИ"}[оп]
            self.e(f"{м} [ДАН], СЧТ")
            return
        if оп == "*":
            self.e("ПЕР АКК, [ДАН]")
            self.e("УМН АКК, СЧТ")
            self.e("ПЕР [ДАН], АКК")
            return
        if оп in ("/", "%"):
            self.e("ПЕР АКК, [ДАН]")
            self.e("ВСТЕК ДАН")  # адрес
            self._глуб += 1
            self.e("РАСШ")
            self.e("ДЕЛ СЧТ")
            if оп == "%":
                self.e("ПЕР АКК, ДАН")
            self.e("ИЗСТЕКА ДАН")
            self._глуб -= 1
            self.e("ПЕР [ДАН], АКК")
            return

    def _если(self, s: N.Если):
        конец = self._новая("есликон")
        for i, (усл, тело) in enumerate(s.рукава):
            след = self._новая("еслисл") if i + 1 < len(s.рукава) or s.иначе else конец
            self._выр(усл)
            self.e("ПРОВ АКК, АКК")
            self.e(f"РАВНО {след}")
            for st in тело:
                self._оп(st)
            self.e(f"ПРЫГ {конец}")
            if след != конец:
                self.метка(след)
        if s.иначе:
            for st in s.иначе:
                self._оп(st)
        self.метка(конец)

    def _пока(self, s: N.Пока):
        нач = self._новая("пока")
        кон = self._новая("покакон")
        self._ctx.циклы.append((нач, кон))
        self.метка(нач)
        self._выр(s.усл)
        self.e("ПРОВ АКК, АКК")
        self.e(f"РАВНО {кон}")
        for st in s.тело:
            self._оп(st)
        self.e(f"ПРЫГ {нач}")
        self.метка(кон)
        self._ctx.циклы.pop()

    def _вечно(self, s: N.Вечно):
        нач = self._новая("вечно")
        кон = self._новая("вечкон")
        self._ctx.циклы.append((нач, кон))
        self.метка(нач)
        for st in s.тело:
            self._оп(st)
        self.e(f"ПРЫГ {нач}")
        self.метка(кон)
        self._ctx.циклы.pop()

    def _для(self, s: N.Для):
        ctx = self._ctx
        if isinstance(s.итер, N.Диап):
            имя = s.имена[0]
            off, t = ctx.локалы[имя]
            предел = ctx.локалы[s._предел][0]
            # направление — если обе границы константны
            try:
                lo = self._конст(s.итер.лев)
                hi = self._конст(s.итер.прав)
                вниз = lo > hi
            except RazError:
                вниз = False
            self._выр(s.итер.лев)
            self._сохранить(f"[УКК-{off}]", N.ЦЕЛ64)
            self._выр(s.итер.прав)
            self._сохранить(f"[УКК-{предел}]", N.ЦЕЛ64)
            нач = self._новая("для")
            шаг = self._новая("дляшаг")
            кон = self._новая("длякон")
            ctx.циклы.append((шаг, кон))
            self.метка(нач)
            self.e(f"ПЕР АКК, [УКК-{off}]")
            self.e(f"СРАВ АКК, [УКК-{предел}]")
            if вниз:
                self.e(f"{'МЕНЬШЕ' if s.итер.вкл else 'МЕНРАВ'} {кон}")
            else:
                self.e(f"{'БОЛЬШЕ' if s.итер.вкл else 'БОЛРАВ'} {кон}")
            for st in s.тело:
                self._оп(st)
            self.метка(шаг)
            self.e(f"{'УМЕН' if вниз else 'УВЕЛ'} КВАД[УКК-{off}]")
            self.e(f"ПРЫГ {нач}")
            self.метка(кон)
            ctx.циклы.pop()
            return
        # для по массиву/срезу: для i, э в масс
        имя_i = s.имена[0]
        off_i, _ = ctx.локалы[имя_i]
        предел = ctx.локалы[s._предел][0]
        t_ит = self._реш_тип(self._тип_выр(s.итер))
        if t_ит.вид == "масс":
            n = t_ит.n
            self.e(f"ПЕР АКК, {n}")
            self._сохранить(f"[УКК-{предел}]", N.ЦЕЛ64)
        elif t_ит.вид == "срез":
            self._выр(s.итер)
            self.e("ПЕР АКК, [АКК+8]")  # .длина
            self._сохранить(f"[УКК-{предел}]", N.ЦЕЛ64)
        else:
            raise RazError("«для в» — по диапазону, массиву или срезу", s.строка)
        self.e("ПЕР АКК, 0")
        self._сохранить(f"[УКК-{off_i}]", N.ЦЕЛ64)
        нач = self._новая("для")
        шаг = self._новая("дляшаг")
        кон = self._новая("длякон")
        ctx.циклы.append((шаг, кон))
        self.метка(нач)
        self.e(f"ПЕР АКК, [УКК-{off_i}]")
        self.e(f"СРАВ АКК, [УКК-{предел}]")
        self.e(f"БОЛРАВ {кон}")
        if len(s.имена) == 2:
            имя_э = s.имена[1]
            off_э, t_э = ctx.локалы[имя_э]
            э = self._индекс_адрес(N.Индекс(s.итер, N.Имя(имя_i)))
            self._загрузить("[АКК]", э)
            self._сохранить(f"[УКК-{off_э}]", t_э)
        for st in s.тело:
            self._оп(st)
        self.метка(шаг)
        self.e(f"УВЕЛ КВАД[УКК-{off_i}]")
        self.e(f"ПРЫГ {нач}")
        self.метка(кон)
        ctx.циклы.pop()

    def _выбор(self, s: N.Выбор):
        ctx = self._ctx
        off = ctx.локалы[s._слот][0]
        self._выр(s.выр)
        self._сохранить(f"[УКК-{off}]", N.ЦЕЛ64)
        конец = self._новая("выбкон")
        метки_тел = [self._новая("выбтело") for _ in s.варианты]
        деф = self._новая("выбиначе") if s.иначе else конец
        for (образцы, _), мт in zip(s.варианты, метки_тел):
            for обр in образцы:
                if isinstance(обр, N.Диап):
                    ложь = self._новая("выбмимо")
                    self.e(f"ПЕР АКК, [УКК-{off}]")
                    self.e("ВСТЕК АКК")
                    self._глуб += 1
                    self._выр(обр.лев)
                    self.e("ПЕР СЧТ, АКК")
                    self.e("ИЗСТЕКА АКК")
                    self._глуб -= 1
                    self.e("СРАВ АКК, СЧТ")
                    self.e(f"МЕНЬШЕ {ложь}")
                    self.e(f"ПЕР АКК, [УКК-{off}]")
                    self.e("ВСТЕК АКК")
                    self._глуб += 1
                    self._выр(обр.прав)
                    self.e("ПЕР СЧТ, АКК")
                    self.e("ИЗСТЕКА АКК")
                    self._глуб -= 1
                    self.e("СРАВ АКК, СЧТ")
                    self.e(f"{'БОЛЬШЕ' if обр.вкл else 'БОЛРАВ'} {ложь}")
                    self.e(f"ПРЫГ {мт}")
                    self.метка(ложь)
                else:
                    self._выр(обр)
                    self.e(f"СРАВ АКК, [УКК-{off}]")
                    self.e(f"РАВНО {мт}")
        self.e(f"ПРЫГ {деф}")
        for (_, тело), мт in zip(s.варианты, метки_тел):
            self.метка(мт)
            for st in тело:
                self._оп(st)
            self.e(f"ПРЫГ {конец}")
        if s.иначе:
            self.метка(деф)
            for st in s.иначе:
                self._оп(st)
        self.метка(конец)

