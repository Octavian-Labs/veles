    def _объяви_запись(self, d: N.ЗаписьДек):
        off = 0
        поля: dict[str, tuple[int, N.Тип]] = {}
        for p in d.поля:
            t = self._реш_тип(p.тип)
            sz = self.размер(t)
            ал = min(8, sz) or 1
            off = (off + ал - 1) // ал * ал
            поля[p.имя] = (off, t)
            off += sz
        размер = (off + 7) // 8 * 8
        self.записи[d.имя] = (размер, поля)

    def _функ(self, f: N.Функ):
        ctx = _Контекст()
        ctx.возвр = f.возвр
        self._ctx = ctx
        if f.приёмник is not None:
            rt = self._реш_тип(f.приёмник.тип)
            rec = self._реш_тип(rt.база).имя if rt.вид == "указ" else rt.имя
            имя_асм = f"ф_{rec}_{f.имя}"
            парамы = [N.Парам(f.приёмник.имя, N.указ(N.запись(rec)))] + list(
                f.параметры
            )
        else:
            имя_асм = f"ф_{f.имя}"
            парамы = f.параметры
        # параметры: [УКК+16+8*i] (win — домашняя область; linux — со сдвигом)
        nreg = len(self.арг_реги)
        стек_парам = max(0, len(парамы) - nreg)
        for i, p in enumerate(парамы):
            if self.target == "windows":
                ctx.парамы[p.имя] = (16 + 8 * i, p.тип)
            else:
                o = 16 + 8 * (i - nreg) if i >= nreg else 16 + 8 * (стек_парам + i)
                ctx.парамы[p.имя] = (o, p.тип)
        # порядок локальных: скан тела (параметры уже видны — иначе `x := парам`
        # не резолвится)
        порядок: list = []
        имена: set = set()
        self._скан_тело(f.тело, порядок, имена)
        # размещение локалов вниз от УКК: база слота размера sz — [УКК-(off+sz-8)]
        off = 8
        for имя, t, выр in порядок:
            if t is None:
                t = self._тип_выр(выр) if выр is not None else N.ЦЕЛ64
            t = self._реш_тип(t)
            sz = max(8, (self.размер(t) + 7) // 8 * 8)
            ctx.локалы[имя] = (off + sz - 8, t)
            off += sz
        локалов = off - 8
        ctx.фрейм = (локалов + 15) // 16 * 16
        ctx.выход = self._новая("выход")
        # пролог
        self.метка(имя_асм)
        self.e("ВСТЕК УКК")
        self.e("ПЕР УКК, УКС")
        if ctx.фрейм:
            self.e(f"ВЫЧ УКС, {ctx.фрейм}")
        # домашнее сохранение регистровых параметров
        for i, p in enumerate(парамы[:nreg]):
            рег = self.арг_реги[i]
            sz = self.размер(p.тип)
            регимя = {8: рег, 4: рег + "М", 2: рег + "П", 1: рег + "Б"}[
                max(1, min(sz, 8))
            ]
            self.e(f"ПЕР [УКК+{ctx.парамы[p.имя][0]}], {регимя}")
        # тело
        for s in f.тело:
            self._оп(s)
        # эпилог
        self.метка(ctx.выход)
        for d in reversed(ctx.отложи):
            self._выр(d)
        self.e("ПОКИНЬ")
        self.e("ВОЗВРАТ")

    def _старт(self):
        """Точка входа: вызывает главная() и завершает процесс её кодом."""
        self.метка("старт")
        if self.target == "windows":
            self.e("ВЫЧ УКС, 8")
            self.e("ВЫЗОВ ф_главная")
            self.e("ПЕР СЧТМ, АККМ")
            self.e("ВЫЗОВ ExitProcess")
        else:
            self.e("ВЫЗОВ ф_главная")
            self.e("ПЕР ПРМ, АКК")
            self.e("ПЕР АКК, 60")
            self.e("СИСВЫЗОВ")

    def _стд_хелперы(self):
        """Системные помощники: выдели/освободи (куча с заголовком размера)."""
        if self.target == "windows":
            if "выдели" in self.нужны_стд:
                self.метка("стд_выдели")  # СЧТ=размер -> АКК=указ
                self.e("ВСТЕК УКК")
                self.e("ПЕР УКК, УКС")
                self.e("ВЫЧ УКС, 48")
                self.e("ПЕР [УКС+32], СЧТ")
                self.e("ВЫЗОВ GetProcessHeap")
                self.e("ПЕР СЧТ, АКК")
                self.e("ПЕР ДАН, 8")  # HEAP_ZERO_MEMORY
                self.e("ПЕР Р8, [УКС+32]")
                self.e("ДОБ Р8, 16")
                self.e("ВЫЗОВ HeapAlloc")
                self.e("ПРОВ АКК, АКК")
                ок = self._новая("выдок")
                self.e(f"РАВНО {ок}")
                self.e("ПЕР СЧТ, [УКС+32]")
                self.e("ПЕР [АКК], СЧТ")  # заголовок: размер
                self.e("ДОБ АКК, 16")
                self.метка(ок)
                self.e("ПОКИНЬ")
                self.e("ВОЗВРАТ")
            if "освободи" in self.нужны_стд:
                self.метка("стд_освободи")  # СЧТ=указ
                self.e("ВСТЕК УКК")
                self.e("ПЕР УКК, УКС")
                self.e("ВЫЧ УКС, 48")
                self.e("ПЕР [УКС+32], СЧТ")
                self.e("ВЫЗОВ GetProcessHeap")
                self.e("ПЕР СЧТ, АКК")
                self.e("ПЕР ДАН, 0")
                self.e("ПЕР Р8, [УКС+32]")
                self.e("ВЫЧ Р8, 16")
                self.e("ВЫЗОВ HeapFree")
                self.e("ПОКИНЬ")
                self.e("ВОЗВРАТ")
        else:
            if "выдели" in self.нужны_стд:
                self.метка("стд_выдели")  # СЧТ=размер -> АКК=указ (mmap)
                self.e("ПЕР ИСТ, СЧТ")
                self.e("ДОБ ИСТ, 16")
                self.e("ВСТЕК ИСТ")
                self.e("ПЕР АКК, 9")  # mmap
                self.e("ПЕР ПРМ, 0")
                self.e("ПЕР ДАН, 3")  # RW
                self.e("ПЕР Р10, 0x22")  # PRIVATE|ANON
                self.e("ПЕР Р8, -1")
                self.e("ПЕР Р9, 0")
                self.e("СИСВЫЗОВ")
                self.e("ИЗСТЕКА ИСТ")
                self.e("ПЕР [АКК], ИСТ")
                self.e("ДОБ АКК, 16")
                self.e("ВОЗВРАТ")
            if "освободи" in self.нужны_стд:
                self.метка("стд_освободи")  # СЧТ=указ (munmap)
                self.e("ВЫЧ СЧТ, 16")
                self.e("ПЕР ИСТ, [СЧТ]")
                self.e("ПЕР ПРМ, СЧТ")
                self.e("ПЕР АКК, 11")  # munmap
                self.e("СИСВЫЗОВ")
                self.e("ВОЗВРАТ")

    # --- программа ------------------------------------------------------------

    def генерируй(self, прог: N.Программа) -> str:
        """Полный текст ИСКРЫ для программы."""
        # проход 1: объявления типов и сигнатур
        for d in прог.decls:
            if isinstance(d, N.ЗаписьДек):
                self._объяви_запись(d)
            elif isinstance(d, N.ТипСин):
                self.синонимы[d.имя] = d.тип
            elif isinstance(d, N.Конст):
                self.консты[d.имя] = self._конст(d.выр)
            elif isinstance(d, N.Переч):
                значения = {}
                след = 0
                for эл in d.элементы:
                    if isinstance(эл, tuple):
                        след = self._конст(эл[1])
                        значения[эл[0]] = след
                    else:
                        значения[эл] = след
                    след += 1
                self.перечи[d.имя] = значения
            elif isinstance(d, N.Внеш):
                funcs = self.импорты.setdefault(d.dll, [])
                if d.имя not in funcs:
                    funcs.append(d.имя)
                self.функции[d.имя] = (d.параметры, d.возвр, True)
            elif isinstance(d, N.Функ):
                if d.приёмник is not None:
                    rt = self._реш_тип(d.приёмник.тип)
                    if rt.вид == "указ" and self._реш_тип(rt.база).вид == "запись":
                        rec = self._реш_тип(rt.база).имя
                    elif rt.вид == "запись":
                        rec = rt.имя
                    else:
                        raise RazError(
                            "приёмник метода должен быть записью или *запись",
                            d.строка,
                        )
                    # приёмник передаётся первым аргументом как *запись
                    парамы = [N.Парам(d.приёмник.имя, N.указ(N.запись(rec)))] + list(
                        d.параметры
                    )
                    self.методы[(rec, d.имя)] = (f"ф_{rec}_{d.имя}", парамы, d.возвр)
                    self.функции[f"{rec}.{d.имя}"] = (парамы, d.возвр, False)
                else:
                    self.функции[d.имя] = (d.параметры, d.возвр, False)
        # автоматические импорты std-помощников и завершения
        if self.target == "windows":
            авто = self.импорты.setdefault("kernel32", [])
            for f in ("ExitProcess",):
                if f not in авто:
                    авто.append(f)
            if self.нужны_стд:
                pass  # импорты хелперов добавим после генерации функций
        # проход 2: код функций (до генерации узнаем нужные стд-функции)
        код_функций = self.код
        for d in прог.decls:
            if isinstance(d, N.Функ):
                if d.имя == "главная":
                    self._есть_главная = True
                self._функ(d)
        # std-хелперы могли понадобиться — импорты
        if self.target == "windows" and self.нужны_стд:
            авто = self.импорты.setdefault("kernel32", [])
            for f in ("GetProcessHeap", "HeapAlloc", "HeapFree"):
                if f not in авто:
                    авто.append(f)
        self._стд_хелперы()
        if self._есть_главная:
            self._старт()
        else:
            raise RazError("программе нужна функция «главная»")
        # сборка текста
        шапка = ["; сгенерировано компилятором РАЗУМ", "СЕКЦИЯ код"]
        for dll, funcs in self.импорты.items():
            шапка.append(f'ИМПОРТ "{dll}" {", ".join(funcs)}')
        if self._есть_главная:
            шапка.append("ВХОД старт")
        тело_текст = шапка + (_пипхол(код_функций) if self.опт > 0 else код_функций)
        if self.данные:
            тело_текст.append("СЕКЦИЯ данные")
            тело_текст += self.данные
        return "\n".join(тело_текст) + "\n"


