# --- peephole-оптимизация ---------------------------------------------------
# Зеркало raz/опт.раз: локальные переписывания шаблонов над списком строк ИСКРЫ.
# Метки и не-инструкции — барьеры окон; ручные искра:-блоки проходят без вреда.

_ОПТ_ЗАПИСЬ = {"ПЕР", "АДР", "БЕЗРАСШ", "БЕЗРАСШД", "ЗНАКРАСШ", "ЗНАКРАСШД"}
_ОПТ_КОММУТ = {"ДОБ", "УМН", "И", "ИЛИ", "ИИЛИ"}
_ОПТ_АКК = {"АКК", "АККМ", "АККД", "АККБ"}
_ОПТ_РЕГ64 = {
    "АКК", "СЧТ", "ДАН", "УКК", "УКС", "ИСТ", "ПРМ",
    "Р8", "Р9", "Р10", "Р11", "Р12", "Р13", "Р14", "Р15",
}
_ОПТ_ИНВ = {
    "РАВНО": "НЕРАВНО", "НЕРАВНО": "РАВНО",
    "МЕНЬШЕ": "БОЛРАВ", "МЕНРАВ": "БОЛЬШЕ",
    "БОЛЬШЕ": "МЕНРАВ", "БОЛРАВ": "МЕНЬШЕ",
    "НИЖЕ": "НЕНИЖЕ", "НИЖРАВ": "ВЫШЕ",
    "ВЫШЕ": "НИЖРАВ", "ВЫШРАВ": "НИЖЕ",
}


def _опт_тело(л: str) -> str:
    """Тело инструкции без отступа; '' — метка/директива/пустая строка."""
    if л.startswith("    "):
        т = л[4:]
        if т and not т.endswith(":"):
            return т
    return ""


def _опт_метка(л: str) -> str:
    """Имя метки (строка «имя:» с отступом или без); '' — не метка."""
    т = л[4:] if л.startswith("    ") else л
    return т[:-1] if т.endswith(":") else ""


def _опт_оп(т: str):
    """(мнемоника, оп1, оп2); оп2='' при одном операнде."""
    м, _, ост = т.partition(" ")
    оп1, _, оп2 = ост.partition(", ")
    return м, оп1, оп2


def _опт_цель_ок(цель: str) -> bool:
    """Переход можно переписывать: цель — сгенерированная метка «м<цифра>_*»,
    на входе которой АКК не несёт булево значение — метки-срезки «и»/«или»
    (иист/иложь) читают АКК сразу после метки."""
    return (
        len(цель) >= 4 and цель[0] == "м" and цель[1].isdigit()
        and not цель.endswith("_иист") and not цель.endswith("_иложь")
    )


def _опт_проход(лини: list):
    """Один проход переписываний; возвращает (список, было_изменение)."""
    вых: list = []
    изм = False
    n = len(лини)
    i = 0

    def т(k: int) -> str:
        return _опт_тело(лини[k]) if k < n else ""

    while i < n:
        л = лини[i]
        т0 = _опт_тело(л)
        if not т0:
            вых.append(л)
            i += 1
            continue
        т1, т2, т3, т4 = т(i + 1), т(i + 2), т(i + 3), т(i + 4)

        # «не x» в условии: ПРОВ; УСТРАВНО; БЕЗРАСШ; ПРОВ; jcc -> ПРОВ; jcc'
        if (т0 == "ПРОВ АКК, АКК" and т1 == "УСТРАВНО АККБ"
                and т2 == "БЕЗРАСШ АКК, АККБ" and т3 == "ПРОВ АКК, АКК"
                and (т4.startswith("РАВНО ") or т4.startswith("НЕРАВНО "))
                and _опт_цель_ок(т4.split(" ", 1)[1])):
            лбл = т4.split(" ", 1)[1]
            дж = "НЕРАВНО" if т4.startswith("РАВНО") else "РАВНО"
            вых.append(л)
            вых.append(f"    {дж} {лбл}")
            изм = True
            i += 5
            continue

        # сравнение в условии: УСТcc; БЕЗРАСШ; ПРОВ; РАВНО/НЕРАВНО -> jcc
        if (т0.startswith("УСТ") and т0.endswith(" АККБ")
                and т1 == "БЕЗРАСШ АКК, АККБ" and т2 == "ПРОВ АКК, АКК"
                and (т3.startswith("РАВНО ") or т3.startswith("НЕРАВНО "))
                and _опт_цель_ок(т3.split(" ", 1)[1])):
            cc = т0[3:т0.index(" ")]
            дж = _ОПТ_ИНВ.get(cc, "")
            if т3.startswith("НЕРАВНО") and дж:
                дж = cc
            if дж:
                вых.append(f"    {дж} {т3.split(' ', 1)[1]}")
                изм = True
                i += 4
                continue

        # сэндвич бинопа: ВСТЕК АКК; ОП АКК*,X; ПЕР СЧТ,АКК; ИЗСТЕКА АКК
        #   -> ОП СЧТ*,X   (АКК держит левый операнд, стек не тронут)
        if (т0 == "ВСТЕК АКК" and т2 == "ПЕР СЧТ, АКК"
                and т3 == "ИЗСТЕКА АКК" and т1):
            м, оп1, оп2 = _опт_оп(т1)
            if м in _ОПТ_ЗАПИСЬ and оп1 in _ОПТ_АКК and оп2 and "УКС" not in т1:
                вых.append(f"    {м} СЧТ{оп1[3:]}, {оп2}")
                изм = True
                i += 4
                continue

        # сэндвич индексации: ВСТЕК АКК; ОП АКК*,X; ИЗСТЕКА СЧТ; КОММУТ АКК,СЧТ
        #   -> ОП СЧТ*,X; КОММУТ АКК,СЧТ   (коммутативность меняет порядок)
        if (т0 == "ВСТЕК АКК" and т2 == "ИЗСТЕКА СЧТ" and т1 and т3):
            м, оп1, оп2 = _опт_оп(т1)
            к, коп1, коп2 = _опт_оп(т3)
            if (м in _ОПТ_ЗАПИСЬ and оп1 in _ОПТ_АКК and оп2
                    and "УКС" not in т1
                    and к in _ОПТ_КОММУТ and коп1 == "АКК" and коп2 == "СЧТ"):
                вых.append(f"    {м} СЧТ{оп1[3:]}, {оп2}")
                вых.append(лини[i + 3])
                изм = True
                i += 4
                continue

        # сэндвич с выгрузкой в другой регистр (Q не АКК/СЧТ):
        #   ВСТЕК АКК; ОП АКК*,X; ПЕР СЧТ,АКК; ИЗСТЕКА Q
        #   -> ПЕР Q,АКК; ОП АКК*,X; ПЕР СЧТ,АКК   (4 -> 3, та же семантика)
        if (т0 == "ВСТЕК АКК" and т2 == "ПЕР СЧТ, АКК"
                and т3.startswith("ИЗСТЕКА ") and т1):
            рп = т3.split(" ", 1)[1]
            м, оп1, оп2 = _опт_оп(т1)
            if (м in _ОПТ_ЗАПИСЬ and оп1 in _ОПТ_АКК and оп2
                    and рп in _ОПТ_РЕГ64 and рп != "СЧТ" and "УКС" not in т1):
                вых.append(f"    ПЕР {рп}, АКК")
                вых.append(лини[i + 1])
                вых.append("    ПЕР СЧТ, АКК")
                изм = True
                i += 4
                continue

        # переход на следующую метку: ПРЫГ L + (метки)*L: -> убрать ПРЫГ
        if т0.startswith("ПРЫГ "):
            цель = т0[5:]
            j = i + 1
            нашли = False
            while j < n:
                м2 = _опт_метка(лини[j])
                if not м2:
                    break
                if м2 == цель:
                    нашли = True
                    break
                j += 1
            if нашли:
                изм = True
                i += 1
                continue
            вых.append(л)
            i += 1
            # мёртвый код после безусловного перехода до ближайшей метки
            while i < n and _опт_тело(лини[i]):
                изм = True
                i += 1
            continue

        # мёртвый код после ВОЗВРАТ/СТОП
        if т0 in ("ВОЗВРАТ", "СТОП"):
            вых.append(л)
            i += 1
            while i < n and _опт_тело(лини[i]):
                изм = True
                i += 1
            continue

        # смежные ВСТЕК X / ИЗСТЕКА Y -> ПЕР Y,X (или ничего при X==Y)
        if т0.startswith("ВСТЕК ") and т1.startswith("ИЗСТЕКА "):
            рв, рп = т0[6:], т1[8:]
            изм = True
            if рв != рп:
                вых.append(f"    ПЕР {рп}, {рв}")
            i += 2
            continue

        # ПЕР Q,... / ИЗСТЕКА Q — запись затёрта снятием со стека
        if т0.startswith("ПЕР ") and т1.startswith("ИЗСТЕКА "):
            if _опт_оп(т0)[1] == т1[8:]:
                вых.append(лини[i + 1])
                изм = True
                i += 2
                continue

        # ПЕР-пары
        if т0.startswith("ПЕР ") and т1.startswith("ПЕР "):
            _, оп1, оп2 = _опт_оп(т0)
            _, п1, п2 = _опт_оп(т1)
            if оп2 and п2:
                # ПЕР X,X — холостой ход (только 64-битные: ПЕР АККМ,АККМ
                # зануляет старшие разряды и не является no-op)
                if оп1 == оп2 and (оп1 in _ОПТ_РЕГ64 or "[" in оп1):
                    изм = True
                    i += 1
                    continue
                # ПЕР A,B; ПЕР B,A — вторая пустая, если B не ссылается на A
                if оп1 == п2 and оп2 == п1 and оп1 not in оп2:
                    вых.append(л)
                    изм = True
                    i += 2
                    continue
                # две одинаковые загрузки — вторая пустая, если источник
                # не зависит от приёмника (ПЕР АКК,[АКК] — разыменование!)
                if т0 == т1 and оп1 not in оп2:
                    вых.append(л)
                    изм = True
                    i += 2
                    continue
                # ПЕР R1,[X]; ПЕР R2,[X] -> ПЕР R1,[X]; ПЕР R2,R1
                if (оп2 == п2 and "[" in оп2
                        and оп1 in _ОПТ_РЕГ64 and п1 in _ОПТ_РЕГ64
                        and оп1 not in оп2):
                    вых.append(л)
                    вых.append(f"    ПЕР {п1}, {оп1}")
                    изм = True
                    i += 2
                    continue

        вых.append(л)
        i += 1
    return вых, изм


def _пипхол(лини: list) -> list:
    """Проходы переписываний до стабилизации."""
    for _ in range(16):
        лини, изм = _опт_проход(лини)
        if not изм:
            break
    return лини


def generate(прог: N.Программа, target: str = "windows", опт: int = 1) -> str:
    """AST -> текст ИСКРЫ."""
    return Генератор(target, опт).генерируй(прог)
